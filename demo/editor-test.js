export async function testEditor(card, original, hass) {
  const check=(value,message)=>{if(!value)throw Error('Editor: '+message)};
  const editor=card.constructor.getConfigElement();
  const input={...original,custom_option:'keep',system:{...original.system,override:true,value:'sensor.grid'},elements:original.elements.map(element=>({...element}))};
  const snapshot=JSON.stringify(input);
  const host=document.createElement('div');host.hidden=true;host.append(editor);document.body.append(host);
  editor.hass=hass;editor.setConfig(input);
  let latest=input;let events=0;
  host.addEventListener('config-changed',event=>{latest=event.detail.config;events++;check(event.bubbles&&event.composed,'changes bubble through shadow roots')});
  await editor.updateComplete;
  const change=async(form,value)=>{form.dispatchEvent(new CustomEvent('value-changed',{detail:{value},bubbles:true,composed:true}));await editor.updateComplete};
  const sensorForms=()=>editor.shadowRoot.querySelector('.sensor').querySelectorAll('ha-form');
  await change(editor.shadowRoot.querySelector('section ha-form'),{...input,title:'Browser title',speed:4});
  check(latest.title==='Browser title'&&latest.speed===4,'card settings update');
  check(latest.custom_option==='keep'&&latest.system.value==='sensor.grid','unknown keys and system override survive');
  const speed=editor.shadowRoot.querySelector('section ha-form').shadowRoot.querySelector('[name=speed]');
  speed.value='2.5';speed.dispatchEvent(new Event('change'));await editor.updateComplete;
  check(latest.speed===2.5,'form controls update numeric settings');
  await change(sensorForms()[0],{value:'sensor.grid'});
  check(latest.elements[0].value==='sensor.grid','entity picker updates power sensor');
  const color=editor.shadowRoot.querySelector('.sensor input[type=color]');color.value='#123456';color.dispatchEvent(new Event('input'));await editor.updateComplete;
  check(latest.elements[0].color==='#123456','color picker updates node');
  const split=editor.shadowRoot.querySelector('.sensor input[type=checkbox]');split.checked=true;split.dispatchEvent(new Event('change'));await editor.updateComplete;
  check(latest.elements[0].value.toSystem==='sensor.grid','split mode keeps existing sensor');
  await change(sensorForms()[0],{toSystem:'sensor.solar',fromSystem:'sensor.home'});
  check(latest.elements[0].value.fromSystem==='sensor.home','split sensor fields update');
  await change(sensorForms()[2],{main:'sensor.soc',left:'sensor.grid'});
  check(latest.elements[0].extra.left==='sensor.grid','extra sensors update');
  check(latest.system.extra===original.system.extra,'unrelated string extras stay unchanged');
  editor.shadowRoot.querySelector('.add').click();await editor.updateComplete;
  check(latest.elements.length===input.elements.length+1,'sensor added');
  editor.shadowRoot.querySelectorAll('.remove')[1].click();await editor.updateComplete;
  check(latest.elements.length===input.elements.length,'sensor removed');
  const invalid={...latest,elements:[{value:'sensor.solar',position:'top'},{value:'sensor.grid',position:'top'},{value:'sensor.home',position:'right'}]};
  editor.setConfig(invalid);await editor.updateComplete;
  const before=events;
  await change(editor.shadowRoot.querySelectorAll('.sensor')[2].querySelectorAll('ha-form')[1],{position:'top'});
  check(events===before&&editor.shadowRoot.querySelector('[role=alert]'),'top row limit is enforced');
  editor.setConfig({...latest,elements:[{value:'sensor.solar',position:'left'}]});await editor.updateComplete;
  check(editor.shadowRoot.querySelector('.remove').disabled,'last sensor cannot be removed');
  check(JSON.stringify(input)===snapshot,'editing does not mutate incoming config');
  check(card.constructor.getStubConfig({states:{}}).elements.length===1,'new card has editable defaults without sensors');
  host.remove();
}
